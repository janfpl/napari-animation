"""Preset routines: keyframe recipes that can be saved and applied to new data.

A routine describes an animation in data-independent terms, so the same
routine produces the same motion on any 3D volume:

* ``sections`` -- the ortho slices the routine uses, each with a world-axis
  normal, a render mode and a thickness given as a fraction of the data
  extent along that normal;
* ``keyframes`` -- for every keyframe the number of frames leading to it,
  its easing, each section's centre as a fraction of the extent along its
  normal (``0`` at one end of the data, ``1`` at the other), whether each
  section is shown, and the camera as a view and up direction plus a zoom
  relative to the zoom that fits the data.

Routines are plain JSON. Built-in routines are generated by code; user
routines are saved in :func:`routines_dir`. Applying a routine replaces the
animation's keyframes and scene objects.
"""

from __future__ import annotations

import json
import re
import warnings
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np

from .easing import Easing

ROUTINE_FORMAT = "napari-animation-routine"
ROUTINE_VERSION = 1

#: World-axis normals of the three ortho views, ordered (z, y, x).
VIEW_NORMALS = {
    "XY": (1.0, 0.0, 0.0),
    "XZ": (0.0, 1.0, 0.0),
    "YZ": (0.0, 0.0, 1.0),
}


# --------------------------------------------------------------- camera math


def _unit(vector) -> np.ndarray:
    vector = np.asarray(vector, dtype=float)
    return vector / np.linalg.norm(vector)


def head_on_camera(normal) -> dict:
    """A camera looking straight at a plane with world-axis ``normal``.

    Napari's 3D camera looks along ``-z`` at zero angles, so looking down a
    normal means a view direction of ``-normal``. The up direction is the
    next world axis, which keeps image rows upright for XY.
    """
    view = -_unit(normal)
    axis = int(np.argmax(np.abs(view)))
    up = np.zeros(3)
    up[1 if axis != 1 else 0] = -1.0
    return {"view": view.tolist(), "up": up.tolist()}


def swung_camera(camera: dict, degrees: float) -> dict:
    """Rotate a camera's view direction about its up axis by ``degrees``."""
    view = _unit(camera["view"])
    up = _unit(camera["up"])
    up = _unit(up - np.dot(up, view) * view)
    angle = np.radians(degrees)
    # Rodrigues' rotation of ``view`` about ``up``.
    rotated = view * np.cos(angle) + np.cross(up, view) * np.sin(angle)
    return {"view": _unit(rotated).tolist(), "up": up.tolist()}


def between_camera(normal_a, normal_b) -> dict:
    """A camera looking halfway between two head-on views."""
    view = -_unit(_unit(normal_a) + _unit(normal_b))
    a, b = int(np.argmax(np.abs(normal_a))), int(np.argmax(np.abs(normal_b)))
    third = ({0, 1, 2} - {a, b}).pop()
    up = np.zeros(3)
    up[third] = -1.0
    return {"view": view.tolist(), "up": up.tolist()}


# -------------------------------------------------------- built-in routines


def ortho_clip_pan_routine(
    pass_seconds: float = 10.0,
    move_seconds: float = 1.5,
    fps: float = 24,
    swing_degrees: float = 15.0,
    thickness: float = 0.1,
    pair_round_trips: int = 2,
) -> dict:
    """Three orthogonal clip slabs panning through the volume.

    Each one-way pass takes ``pass_seconds`` and each camera move
    ``move_seconds`` at ``fps``; ``thickness`` is the slab thickness as a
    fraction of the data extent along its normal.

    Phase 1 takes the slabs one at a time while the other two stay parked
    at the centre: a round trip seen head-on, then a round trip while the
    camera swings from ``-swing_degrees`` to ``+swing_degrees`` about the
    head-on view. Phase 2 pans the slabs two at a time, ``pair_round_trips``
    round trips per pair, seen from halfway between the two planes.
    """
    pass_frames = max(1, round(pass_seconds * fps))
    move_frames = max(1, round(move_seconds * fps))
    keys = list(VIEW_NORMALS)
    centre = {key: 0.5 for key in keys}
    keyframes: List[dict] = []

    def add(name, steps, positions, camera, ease="SINE"):
        keyframes.append(
            {
                "name": name,
                "steps": int(steps),
                "ease": ease,
                "sections": {key: float(positions[key]) for key in keys},
                "camera": camera,
            }
        )

    for key in keys:
        head_on = head_on_camera(VIEW_NORMALS[key])
        left = swung_camera(head_on, -swing_degrees)
        right = swung_camera(head_on, swing_degrees)
        at = dict(centre)
        add(f"{key} start", move_frames, {**at, key: 0.0}, head_on)
        add(f"{key} far end", pass_frames, {**at, key: 1.0}, head_on)
        add(f"{key} back", pass_frames, {**at, key: 0.0}, head_on)
        add(f"{key} swing left", move_frames, {**at, key: 0.0}, left)
        add(f"{key} swing right", pass_frames, {**at, key: 1.0}, right)
        add(f"{key} swing back", pass_frames, {**at, key: 0.0}, left)

    for a, b in (("XY", "XZ"), ("XZ", "YZ"), ("XY", "YZ")):
        camera = between_camera(VIEW_NORMALS[a], VIEW_NORMALS[b])
        start = {**centre, a: 0.0, b: 0.0}
        end = {**centre, a: 1.0, b: 1.0}
        add(f"{a}+{b} start", move_frames, start, camera)
        for trip in range(pair_round_trips):
            add(f"{a}+{b} far end {trip + 1}", pass_frames, end, camera)
            add(f"{a}+{b} back {trip + 1}", pass_frames, start, camera)

    keyframes[0]["steps"] = 1
    return {
        "format": ROUTINE_FORMAT,
        "version": ROUTINE_VERSION,
        "name": "Ortho clip pans",
        "fps": fps,
        "description": (
            "Three orthogonal clip slabs pan end to end: one at a time "
            "head-on, then with the camera swinging "
            f"±{swing_degrees:g}°, then two at a time."
        ),
        "sections": [
            {
                "key": key,
                "normal": list(VIEW_NORMALS[key]),
                "thickness": thickness,
                "render_mode": "clip",
                "projection": "max",
            }
            for key in keys
        ],
        "keyframes": keyframes,
    }


BUILTIN_ROUTINES = {"Ortho clip pans": ortho_clip_pan_routine}


# --------------------------------------------------------------- storage


def routines_dir() -> Path:
    """Folder holding saved user routines."""
    import platformdirs

    return Path(platformdirs.user_data_dir("napari-animation")) / "routines"


def validate_routine(routine: dict) -> dict:
    """Check a routine's structure and return it; raise ValueError if bad."""
    if not isinstance(routine, dict):
        raise ValueError("A routine must be a JSON object")
    if routine.get("format") != ROUTINE_FORMAT:
        raise ValueError("Not a napari-animation routine")
    if int(routine.get("version", 0)) > ROUTINE_VERSION:
        raise ValueError(
            f"Routine version {routine.get('version')} is newer than this "
            f"plugin supports ({ROUTINE_VERSION})"
        )
    keys = set()
    for section in routine.get("sections", []):
        normal = np.asarray(section["normal"], dtype=float)
        if normal.shape != (3,) or not np.any(normal):
            raise ValueError(f"Section {section.get('key')!r} has no normal")
        if not 0 < float(section.get("thickness", 0.1)) <= 1:
            raise ValueError("Section thickness must be a fraction in (0, 1]")
        keys.add(section["key"])
    if not routine.get("keyframes"):
        raise ValueError("A routine needs at least one keyframe")
    for keyframe in routine["keyframes"]:
        if int(keyframe.get("steps", 1)) < 1:
            raise ValueError("Keyframe steps must be at least 1")
        if (
            str(keyframe.get("ease", "LINEAR")).upper()
            not in Easing.__members__
        ):
            raise ValueError(f"Unknown easing {keyframe.get('ease')!r}")
        unknown = set(keyframe.get("sections", {})) - keys
        if unknown:
            raise ValueError(f"Keyframe refers to unknown sections {unknown}")
    return routine


def _slug(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "-", name).strip("-") or "routine"


def save_routine(routine: dict, path=None) -> Path:
    """Write a routine as JSON (to :func:`routines_dir` by default)."""
    validate_routine(routine)
    if path is None:
        path = routines_dir() / f"{_slug(routine['name'])}.json"
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(routine, indent=2), encoding="utf-8")
    return path


def load_routine(path) -> dict:
    with open(path, encoding="utf-8") as f:
        return validate_routine(json.load(f))


def available_routines(folder=None) -> Dict[str, dict]:
    """Built-in routines followed by saved ones, keyed by display name."""
    routines = {name: make() for name, make in BUILTIN_ROUTINES.items()}
    folder = Path(folder) if folder is not None else routines_dir()
    if folder.is_dir():
        for path in sorted(folder.glob("*.json")):
            try:
                routine = load_routine(path)
            except (OSError, ValueError, KeyError, TypeError):
                continue
            name = routine["name"]
            if name in routines:
                name = f"{name} ({path.stem})"
            routines[name] = routine
    return routines


# --------------------------------------------------------------- applying


def _source_layers(viewer):
    from .layer_registry import (
        MANAGED_ROLE_METADATA,
        OBJECT_ID_METADATA,
    )

    return [
        layer
        for layer in viewer.layers
        if getattr(layer, "_type_string", "") == "image"
        and getattr(layer, "ndim", 0) >= 3
        and not layer.metadata.get(MANAGED_ROLE_METADATA)
        and not layer.metadata.get(OBJECT_ID_METADATA)
    ]


def _world_bounds(layers) -> np.ndarray:
    """``(2, 3)`` world-space bounds of the trailing three axes."""
    extents = np.stack([layer.extent.world[:, -3:] for layer in layers])
    return np.stack([extents[:, 0].min(axis=0), extents[:, 1].max(axis=0)])


def _axis_length(bounds, normal) -> float:
    """Extent of the data box measured along ``normal``."""
    size = bounds[1] - bounds[0]
    return float(np.sum(np.abs(_unit(normal)) * size))


def _centre_at(bounds, normal, fraction) -> np.ndarray:
    """World point at ``fraction`` of the extent along ``normal``."""
    centre = bounds.mean(axis=0)
    unit = _unit(normal)
    half = _axis_length(bounds, unit) / 2.0
    return centre + unit * (2.0 * float(fraction) - 1.0) * half


def _fit_zoom(viewer, animation) -> float:
    animation.fit_view()
    return float(viewer.camera.zoom)


def apply_routine(
    animation, routine: dict, thickness: Optional[float] = None
) -> None:
    """Replace ``animation``'s keyframes and scene with ``routine``.

    Sections are created as composite ortho slices over every 3D image
    layer, sized and positioned from the combined data extent.
    ``thickness``, a fraction of the extent, overrides every section's
    stored thickness.
    """
    if thickness is not None and not 0 < float(thickness) <= 1:
        raise ValueError("Slab thickness must be a fraction in (0, 1]")
    from .scene import OrthoSlice

    validate_routine(routine)
    viewer = animation.viewer
    sources = _source_layers(viewer)
    if not sources:
        raise ValueError("A routine needs at least one 3D image layer")
    bounds = _world_bounds(sources)

    from .layer_registry import LayerRegistry

    channels = {
        LayerRegistry.ensure_id(layer): {
            "source_id": LayerRegistry.ensure_id(layer),
            "source_name": layer.name,
            "enabled": True,
            "source_level": 0,
        }
        for layer in sources
    }

    animation.key_frames.clear()
    for scene_object in list(animation.scene):
        animation.remove_scene_object(scene_object)
    animation.snap_3d(capture=False)
    zoom = _fit_zoom(viewer, animation)

    sections = {}
    for spec in routine.get("sections", []):
        normal = tuple(float(v) for v in _unit(spec["normal"]))
        section = OrthoSlice(
            name=spec.get("name", f"{spec['key']} slab"),
            source=sources[0].name,
            position=tuple(_centre_at(bounds, normal, 0.5).tolist()),
            normal=normal,
            thickness=float(
                thickness
                if thickness is not None
                else spec.get("thickness", 0.1)
            )
            * _axis_length(bounds, normal),
            projection=spec.get("projection", "max"),
            render_mode=spec.get("render_mode", "clip"),
            channels={key: dict(value) for key, value in channels.items()},
        )
        animation.add_scene_object(section, backfill=False)
        sections[spec["key"]] = section

    for keyframe in routine["keyframes"]:
        for key, fraction in keyframe.get("sections", {}).items():
            section = sections[key]
            changes = {
                "position": tuple(
                    _centre_at(bounds, section.normal, fraction).tolist()
                )
            }
            shown = keyframe.get("enabled", {}).get(key, True)
            if bool(shown) != bool(section.enabled):
                changes["enabled"] = bool(shown)
            animation.update_scene_object(section.id, **changes)
        camera = keyframe.get("camera")
        if camera:
            with warnings.catch_warnings():
                # head-on views are gimbal-locked Euler angles; harmless
                warnings.simplefilter("ignore", UserWarning)
                viewer.camera.set_view_direction(
                    tuple(camera["view"]), tuple(camera["up"])
                )
            viewer.camera.zoom = zoom * float(camera.get("zoom", 1.0))
        animation.capture_keyframe(
            steps=int(keyframe.get("steps", 1)),
            ease=Easing[str(keyframe.get("ease", "LINEAR")).upper()],
            position=len(animation.key_frames) - 1,
        )
        if keyframe.get("name"):
            animation.key_frames[-1].name = keyframe["name"]
    animation.set_to_keyframe(0)


# --------------------------------------------------------------- capturing


def routine_from_keyframes(
    animation, name: str, description: str = ""
) -> dict:
    """Describe ``animation``'s keyframes as a data-independent routine.

    Ortho slices become routine sections; their centres and thicknesses are
    stored as fractions of the current data extent. Cameras are stored as
    view and up directions with zoom relative to the fitted zoom. Other
    scene objects (cutaway clip planes) are not part of routines yet and
    are left out.
    """
    from scipy.spatial.transform import Rotation

    viewer = animation.viewer
    sources = _source_layers(viewer)
    if not sources:
        raise ValueError("A routine needs at least one 3D image layer")
    if not len(animation.key_frames):
        raise ValueError("There are no keyframes to save")
    bounds = _world_bounds(sources)
    camera = viewer.camera
    saved = (camera.zoom, tuple(camera.center), tuple(camera.angles))
    try:
        fit = _fit_zoom(viewer, animation)
    finally:
        camera.zoom, camera.center, camera.angles = saved

    sections = {}
    keyframes = []
    for key_frame in animation.key_frames:
        state = key_frame.viewer_state
        entry = {
            "name": key_frame.name,
            "steps": int(key_frame.steps),
            "ease": key_frame.ease.name,
            "sections": {},
            "enabled": {},
        }
        for object_id, params in (state.scene or {}).items():
            if params.get("kind") != "ortho_slice":
                continue
            normal = _unit(params["normal"])
            if object_id not in sections:
                sections[object_id] = {
                    "key": params.get("name") or object_id,
                    "name": params.get("name") or object_id,
                    "normal": normal.tolist(),
                    "thickness": min(
                        1.0,
                        float(params["thickness"])
                        / _axis_length(bounds, normal),
                    ),
                    "render_mode": params.get("render_mode", "plane"),
                    "projection": params.get("projection", "max"),
                }
            key = sections[object_id]["key"]
            centre = bounds.mean(axis=0)
            half = _axis_length(bounds, normal) / 2.0
            offset = np.dot(np.asarray(params["position"]) - centre, normal)
            entry["sections"][key] = float(0.5 + offset / (2.0 * half))
            entry["enabled"][key] = bool(params.get("enabled", True))
        angles = state.camera.get("angles")
        if angles is not None and len(angles) == 3:
            matrix = Rotation.from_euler("xyz", angles, degrees=True)
            matrix = matrix.as_matrix()
            entry["camera"] = {
                "view": (-matrix[0]).tolist(),
                "up": (-matrix[1]).tolist(),
                "zoom": float(state.camera.get("zoom", fit)) / fit,
            }
        keyframes.append(entry)
    return validate_routine(
        {
            "format": ROUTINE_FORMAT,
            "version": ROUTINE_VERSION,
            "name": name,
            "description": description,
            "sections": list(sections.values()),
            "keyframes": keyframes,
        }
    )


def routine_summary(routine: dict, fps: Optional[float] = None) -> str:
    """One line such as ``33 keyframes, 6049 frames (252.0 s at 24 fps)``."""
    fps = fps or routine.get("fps", 24)
    keyframes = routine.get("keyframes", [])
    frames = 1 + sum(int(k.get("steps", 1)) for k in keyframes[1:])
    text = f"{len(keyframes)} keyframes, {frames} frames"
    if fps:
        text += f" ({frames / fps:.1f} s at {fps:g} fps)"
    return text
